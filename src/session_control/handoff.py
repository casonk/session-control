"""Continue a session in a different provider by handing over a context brief.

Providers store transcripts in incompatible formats, so a Codex session cannot be
resumed natively by Claude Code (or the reverse). A handoff instead writes a markdown
brief from the source session and starts a *new* session in the target CLI, told to read
it first. The brief holds the title, workspace and, where the transcript format is
understood (Codex and Claude Code), the most recent conversation turns.
"""

from __future__ import annotations

import json
import os
import shlex
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from session_control.models import SessionRecord
from session_control.redaction import REDACTED, redact
from session_control.scanner import _extract_text, _is_bootstrap_text

# Target provider -> argv prefix that starts an interactive session whose opening prompt is
# appended as the final argument (positional for most CLIs, behind -i for Copilot and AGY).
HANDOFF_TARGETS: dict[str, tuple[str, ...]] = {
    "claude": ("claude",),
    "codex": ("codex",),
    "grok": ("grok",),
    "continue": ("cn",),
    "copilot": ("copilot", "-i"),
    "agy": ("agy", "-i"),
}

MAX_TURNS = 24
MAX_TURN_CHARS = 1500
MAX_BRIEF_CHARS = 24000


class HandoffError(Exception):
    """The handoff cannot be prepared."""


@dataclass(frozen=True)
class Turn:
    role: str
    text: str


def handoff_targets_for(provider: str) -> tuple[str, ...]:
    """Targets offered for a session: every handoff target except its own provider."""
    return tuple(name for name in HANDOFF_TARGETS if name != provider)


def recent_turns(session: SessionRecord, *, limit: int = MAX_TURNS) -> list[Turn]:
    """Return the last conversation turns, or none when the format is not readable."""
    if session.provider == "codex":
        turns = _codex_turns(session.primary_path)
    elif session.provider == "claude":
        turns = _claude_turns(session.primary_path)
    else:
        return []
    return turns[-limit:]


def build_brief(session: SessionRecord, turns: list[Turn]) -> str:
    masked = 0

    def clean(text: str) -> str:
        # Redact before any truncation so a cut can never leave half a secret behind.
        nonlocal masked
        text, count = redact(text)
        masked += count
        return text

    title = clean(session.title or session.session_id)
    turns = [Turn(turn.role, clean(turn.text)) for turn in turns]
    preview = clean(session.preview) if session.preview else ""
    lines = [
        f"# Handoff from {session.provider}: {title}",
        "",
        "This brief was generated by session-control so a different assistant can",
        "continue work that began in another tool. It is a summary, not an exact",
        "transcript: verify the state of the repository before relying on it.",
        "",
        f"- Source provider: {session.provider}",
        f"- Source session id: {session.session_id}",
        f"- Workspace: {session.workspace or 'unknown'}",
        f"- Started: {session.created_at or 'unknown'}",
        f"- Last updated: {session.updated_at or 'unknown'}",
        f"- Messages: {session.message_count}",
        "",
    ]
    if turns:
        lines += ["## Recent conversation", ""]
        for turn in turns:
            lines += [f"### {turn.role}", "", _fence(turn.text), ""]
    elif preview:
        lines += [
            "## Opening message",
            "",
            _fence(preview),
            "",
            f"(The {session.provider} transcript format is not readable, so only the",
            "opening message is available.)",
            "",
        ]
    if masked:
        lines += [
            f"Note: {masked} secret-like value(s) in the source session were replaced with",
            f"{REDACTED}. Ask the user for any credential you need; do not guess.",
            "",
        ]
    brief = "\n".join(lines)
    if len(brief) > MAX_BRIEF_CHARS:
        brief = brief[:MAX_BRIEF_CHARS] + "\n\n[brief truncated]\n"
    return brief


def write_brief(directory: Path, session: SessionRecord, brief: str) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    os.chmod(directory, 0o700)
    path = directory / f"{session.provider}-{session.public_id}.md"
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(brief)
    return path


def handoff_command(session: SessionRecord, target: str, brief_path: Path) -> str:
    if target not in HANDOFF_TARGETS:
        raise HandoffError(
            f"Cannot hand off to {target!r}; choose one of: {', '.join(HANDOFF_TARGETS)}."
        )
    if target == session.provider:
        raise HandoffError(f"This is already a {target} session; use the normal resume.")
    prompt = (
        f"Read {brief_path} first. It is a handoff brief from an earlier {session.provider} "
        "session on this work. Summarize your understanding of where things stand, then "
        "continue from there once I confirm."
    )
    command = " ".join(shlex.quote(part) for part in (*HANDOFF_TARGETS[target], prompt))
    if session.workspace:
        return f"cd {shlex.quote(session.workspace)} && {command}"
    return command


def _fence(text: str) -> str:
    text = text.strip()
    if len(text) > MAX_TURN_CHARS:
        text = text[:MAX_TURN_CHARS] + " [...]"
    fence = "~~~~" if "```" in text else "```"
    return f"{fence}\n{text}\n{fence}"


def _jsonl(path: Path):
    try:
        with path.open("r", encoding="utf-8", errors="replace") as handle:
            for line in handle:
                try:
                    item = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if isinstance(item, dict):
                    yield item
    except OSError:
        return


def _keep(role: str, text: str) -> Turn | None:
    text = text.strip()
    if not text or _is_bootstrap_text(text):
        return None
    return Turn("User" if role == "user" else "Assistant", text)


def _codex_turns(path: Path) -> list[Turn]:
    turns: list[Turn] = []
    for row in _jsonl(path):
        payload: Any = row.get("payload")
        if row.get("type") != "response_item" or not isinstance(payload, dict):
            continue
        role = payload.get("role")
        if payload.get("type") != "message" or role not in ("user", "assistant"):
            continue
        turn = _keep(role, _extract_text(payload.get("content")))
        if turn:
            turns.append(turn)
    return turns


def _claude_turns(path: Path) -> list[Turn]:
    turns: list[Turn] = []
    for row in _jsonl(path):
        role = row.get("type")
        message = row.get("message")
        if role not in ("user", "assistant") or not isinstance(message, dict):
            continue
        content = message.get("content")
        if isinstance(content, list):
            # Skip tool calls and results: only the human-readable text parts matter.
            content = [p for p in content if isinstance(p, dict) and p.get("type") == "text"]
        turn = _keep(role, _extract_text(content))
        if turn:
            turns.append(turn)
    return turns
